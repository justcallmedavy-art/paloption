/**
 * Build the deployable bundle for the API host.
 *
 * The counterpart to `tools/prepare-deploy.mjs`, and the same idea: a host that
 * deploys from this machine must be handed exactly the files the service needs,
 * and nothing else.
 *
 * That "nothing else" is load-bearing here. This working copy is not a Git
 * checkout of the project — the enclosing repository is the user's home
 * directory — so a CLI that uploads the current directory (`railway up`) would
 * otherwise have the whole home folder as its candidate set. The bundle is the
 * boundary that makes an upload well-defined: it is assembled from an explicit
 * list of sources, so no file can arrive by being merely present.
 *
 * What goes in, and why:
 *
 *   tools/            the service itself: the API, the trading socket, the store,
 *                     the payment domain, and schema.sql for the ledger
 *   site/             the mirrored client, served *pristine*. The server applies
 *                     the re-colour and the client patches on the way out, so a
 *                     snapshot here would apply them twice.
 *   package.json      and its lockfile, verbatim: `npm ci --omit=dev` fails if
 *   package-lock.json the two disagree, and only the runtime dep (`pg`) installs
 *   railway.json      builder, start command and the /healthz probe
 *   Procfile          the same start command for Heroku-style hosts
 *
 * What stays out: `.env.local` (credentials are set on the host, never shipped),
 * `node_modules` and `dist` (built on the host), `tests/` and the Tailwind
 * toolchain (dev-only), and `deploy/` itself (the frontend snapshot).
 *
 * Usage: node tools/prepare-api.mjs [--out deploy/api] [--check]
 *   --check   build to a temporary directory and report any difference against
 *             the existing bundle, writing nothing (exit 1 if it differs)
 */
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { basename, dirname, join, relative, resolve } from "node:path";

const argv = process.argv.slice(2);
const check = argv.includes("--check");
const outFlag = argv.indexOf("--out");
const outArg = outFlag === -1 ? "deploy/api" : argv[outFlag + 1];
if (!outArg || outArg === "--check") {
  console.error("usage: node tools/prepare-api.mjs [--out <dir>] [--check]");
  process.exit(2);
}
const outDir = resolve(outArg);

/** Whole directories, copied verbatim. */
const DIRS = ["tools", "site"];

/** Individual files, copied verbatim. */
const FILES = ["package.json", "package-lock.json", "railway.json", "Procfile"];

/**
 * Never copied, whatever else changes.
 *
 * A file that is merely in one of the directories above is not thereby safe to
 * ship: this is the second lock, so adding a stray credential to `site/` or
 * `tools/` cannot silently put it in an upload.
 */
const NEVER = [/^\.env/i, /\.map$/, /\.pem$/, /\.key$/i, /\.log$/i, /^sessions?\.json$/i];

/**
 * Railway (and any uploader) reads `.railwayignore`, falling back to
 * `.gitignore`. The bundle contains none of these today because it is assembled
 * from a list; the rule is here so a later change cannot quietly ship them.
 */
const IGNORE = `# Generated by tools/prepare-api.mjs — the bundle ships no dependencies
# and no credentials. Both are provided by the host.
node_modules/
.env
.env.*
*.log
.data/
`;

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (entry.isFile()) yield path;
  }
}

const excluded = (rel) => NEVER.some((re) => re.test(basename(rel)));

const staging = join(tmpdir(), `strategyoption-api-${process.pid}`);
await rm(staging, { recursive: true, force: true });
await mkdir(staging, { recursive: true });

let files = 0;
let bytes = 0;
const skipped = [];

/** Copies one file into the staging tree, enforcing the NEVER list. */
async function emit(absSource, outRel) {
  if (excluded(outRel)) {
    skipped.push(outRel);
    return;
  }
  const dest = join(staging, outRel);
  await mkdir(dirname(dest), { recursive: true });
  const body = await readFile(absSource);
  await writeFile(dest, body);
  files += 1;
  bytes += body.length;
}

for (const dir of DIRS) {
  const abs = resolve(dir);
  try {
    await readdir(abs);
  } catch {
    throw new Error(`bundle source is missing: ${dir}/`);
  }
  for await (const file of walk(abs)) {
    await emit(file, join(dir, relative(abs, file)));
  }
}

for (const file of FILES) {
  const abs = resolve(file);
  try {
    await readFile(abs);
  } catch {
    throw new Error(`bundle source is missing: ${file}`);
  }
  await emit(abs, file);
}

await writeFile(join(staging, ".railwayignore"), IGNORE);
files += 1;

const kib = (bytes / 1024).toFixed(0);
const summary = `${files} file(s), ${kib} KiB; ${DIRS.join(", ")} verbatim plus ${FILES.join(", ")}`;
if (skipped.length) console.warn(`[prepare-api] excluded ${skipped.length} file(s): ${skipped.join(", ")}`);

if (check) {
  const diffs = [];
  const wanted = new Set();
  for await (const file of walk(staging)) wanted.add(relative(staging, file).split("\\").join("/"));
  for (const rel of wanted) {
    try {
      const [a, b] = await Promise.all([readFile(join(staging, rel)), readFile(join(outDir, rel))]);
      if (!a.equals(b)) diffs.push(`differs  ${rel}`);
    } catch {
      diffs.push(`missing  ${rel}`);
    }
  }
  try {
    for await (const file of walk(outDir)) {
      const rel = relative(outDir, file).split("\\").join("/");
      if (!wanted.has(rel)) diffs.push(`stale    ${rel}`);
    }
  } catch {
    /* no existing bundle is just "everything missing", already reported */
  }
  await rm(staging, { recursive: true, force: true });
  for (const line of diffs) console.log(line);
  console.log(diffs.length ? `out of date: ${summary}` : `up to date: ${summary}`);
  process.exit(diffs.length ? 1 : 0);
}

// Replace the bundle wholesale, so a file that is no longer produced cannot
// survive into an upload.
await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
await cp(staging, outDir, { recursive: true });
await rm(staging, { recursive: true, force: true });

console.log(`wrote ${outDir}: ${summary}`);
